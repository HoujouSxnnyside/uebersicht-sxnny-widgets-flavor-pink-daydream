export async function optimizeAssets() {
  console.log('[assets] Starting Sharp WebP/AVIF optimization for 37 illustration assets...');
  await mkdir(DIST_IMAGES_DIR, { recursive: true });

  const files = (await readdir(IMAGES_DIR))
    .filter((f) => f.endsWith('.png'))
    .sort((a, b) => parseInt(a, 10) - parseInt(b, 10));

  if (files.length === 0) {
    console.log('[assets] No raw PNG assets found. Using pre-optimized WebP/AVIF assets.');
    return;
  }

  let totalPngBytes = 0;
  let totalWebpBytes = 0;
  let totalAvifBytes = 0;

  const webpDataUrls: Record<number, string> = {};

  for (const file of files) {
    const num = parseInt(file.replace('.png', ''), 10);
    const srcPath = join(IMAGES_DIR, file);
    const baseName = `${num}`;
    const webpPath = join(IMAGES_DIR, `${baseName}.webp`);
    const avifPath = join(IMAGES_DIR, `${baseName}.avif`);
    const distWebpPath = join(DIST_IMAGES_DIR, `${baseName}.webp`);

    const pngStat = await stat(srcPath);
    totalPngBytes += pngStat.size;

    // 1. Generate WebP (Ultra-crisp 90% quality with alpha preservation)
    const webpBuffer = await sharp(srcPath)
      .webp({ quality: 90, effort: 6, alphaQuality: 100 })
      .toBuffer();
    await writeFile(webpPath, webpBuffer);
    await writeFile(distWebpPath, webpBuffer);
    totalWebpBytes += webpBuffer.length;

    // 2. Generate AVIF for cutting-edge next-gen storage
    const avifBuffer = await sharp(srcPath).avif({ quality: 82, effort: 6 }).toBuffer();
    await writeFile(avifPath, avifBuffer);
    totalAvifBytes += avifBuffer.length;

    // Store WebP data-URL for zero-latency self-contained bundling
    webpDataUrls[num] = `data:image/webp;base64,${webpBuffer.toString('base64')}`;
  }

  const savingsWebp = ((1 - totalWebpBytes / totalPngBytes) * 100).toFixed(1);
  const savingsAvif = ((1 - totalAvifBytes / totalPngBytes) * 100).toFixed(1);

  console.log(`[assets] Original PNGs: ${(totalPngBytes / 1024).toFixed(1)} KB`);
  console.log(
    `[assets] Optimized WebPs: ${(totalWebpBytes / 1024).toFixed(1)} KB (-${savingsWebp}%)`,
  );
  console.log(
    `[assets] Optimized AVIFs: ${(totalAvifBytes / 1024).toFixed(1)} KB (-${savingsAvif}%)`,
  );

  // 3. Generate TypeScript Asset Registry
  let tsCode = `// Autogenerated by scripts/optimize-assets.ts
// Optimized WebP data-URLs for zero-latency desktop rendering in Übersicht

`;

  // Named exports
  for (const [idStr, constName] of Object.entries(SEMANTIC_NAMES)) {
    const id = parseInt(idStr, 10);
    const url = webpDataUrls[id];
    if (url) {
      tsCode += `export const ${constName} = "${url}";\n`;
    }
  }

  tsCode += `\n/**
 * Complete numeric map of all 37 Pink Daydream illustrations
 */
export const ASSET_MAP: Record<number, string> = {
`;

  for (let i = 1; i <= 37; i++) {
    if (webpDataUrls[i]) {
      const semanticName = SEMANTIC_NAMES[i];
      tsCode += `  ${i}: ${semanticName ? semanticName : `"${webpDataUrls[i]}"`},\n`;
    }
  }

  tsCode += `};\n
export type AssetNumber = keyof typeof ASSET_MAP;
`;

  const indexPath = join(IMAGES_DIR, 'index.ts');
  await writeFile(indexPath, tsCode, 'utf-8');
  try {
    await Bun.$`biome format --write ${indexPath}`.quiet();
  } catch {}
  console.log(`[assets] Registry generated and formatted at: ${indexPath}`);
}

await optimizeAssets();
